"""Validate one real RetinaVLM J-Lens candidate in its readout mode.

This gate uses validation patients only for selection and one training image
for the adapter-gradient check. It records failures rather than relaxing its
fixed thresholds. The candidate must first be generated by the fitter.
"""

from __future__ import annotations

import argparse
import json
import math
import random
from collections import defaultdict
from pathlib import Path

import torch
from torch.nn import functional as F

from fit_retinavlm_fluid_lens_candidate import CANDIDATE_STATUSES, READOUT_QUESTIONS, score_one_image, tensor_for_row
from retinavlm_matched_arm_losses import FixedLensHead, adapter_parameters
from retinavlm_pre_answer import pre_answer_forward
from retinavlm_released_model import SPECIALIST_REVISION, load_released_specialist
from retinavlm_verified_images import load_verified_manifest, select_split, sha256


MIN_VALIDATION_AUC = 0.60
MIN_BOOTSTRAP_AUC_LOWER = 0.50
MIN_SWAP_POSITIVE_FRACTION = 0.60
MAX_JACOBIAN_ABSOLUTE_ERROR = 0.01
MAX_SCORE_RECHECK_ERROR = 0.02


def auc(pairs: list[tuple[int, float]]) -> float:
    positives = sum(label == 1 for label, _ in pairs)
    negatives = sum(label == 0 for label, _ in pairs)
    if not positives or not negatives:
        raise ValueError("AUC requires both fluid classes")
    ordered = sorted(pairs, key=lambda pair: pair[1])
    positive_rank_sum = 0.0
    cursor = 0
    while cursor < len(ordered):
        end = cursor + 1
        while end < len(ordered) and ordered[end][1] == ordered[cursor][1]:
            end += 1
        average_rank = ((cursor + 1) + end) / 2
        positive_rank_sum += average_rank * sum(label == 1 for label, _ in ordered[cursor:end])
        cursor = end
    return (positive_rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def percentile(values: list[float], probability: float) -> float:
    ordered = sorted(values)
    location = (len(ordered) - 1) * probability
    low = int(location)
    high = min(low + 1, len(ordered) - 1)
    return ordered[low] + (ordered[high] - ordered[low]) * (location - low)


def patient_bootstrap_auc(rows: list[dict], layer: str, scale: float,
                          replicates: int, seed: int) -> dict:
    if replicates < 1:
        raise ValueError("Bootstrap needs at least one replicate")
    by_patient = defaultdict(list)
    trial_patients = defaultdict(set)
    for row in rows:
        by_patient[row["Patient_ID"]].append(row)
        trial_patients[row["trial"]].add(row["Patient_ID"])
    rng = random.Random(seed)
    values = []
    for _ in range(replicates):
        sampled = []
        for trial in sorted(trial_patients):
            group = sorted(trial_patients[trial])
            sampled.extend(rng.choice(group) for _ in group)
        observations = [(int(row["fluid"]), scale * float(row["scores"][layer]))
                        for patient in sampled for row in by_patient[patient]]
        try:
            values.append(auc(observations))
        except ValueError:
            continue
    if not values:
        raise ValueError("No valid patient bootstrap replicate contains both classes")
    return {"ci95": [percentile(values, 0.025), percentile(values, 0.975)],
            "valid_replicates": len(values), "requested_replicates": replicates,
            "trial_patient_counts": {trial: len(group) for trial, group in sorted(trial_patients.items())}}


def run(*, model_dir: Path, authors_code: Path, manifest: Path, image_audit: Path,
        image_root: Path, candidate_path: Path, layer_index: int, output: Path,
        bootstrap_replicates: int = 2000) -> dict:
    if output.exists():
        raise FileExistsError("Lens validation receipt already exists")
    rows = load_verified_manifest(manifest, image_audit)
    manifest_digest = sha256(manifest)
    train_rows = sorted(select_split(rows, "train"), key=lambda row: row["source_image_path"])
    validation_rows = sorted(select_split(rows, "validation"), key=lambda row: row["source_image_path"])
    candidate = json.loads(candidate_path.read_text(encoding="utf-8"))
    key = str(layer_index)
    readout_mode = candidate.get("readout_mode")
    question = READOUT_QUESTIONS.get(readout_mode)
    if (candidate.get("status") != CANDIDATE_STATUSES.get(readout_mode)
            or question is None or candidate.get("question") != question
            or candidate.get("checkpoint_revision") != SPECIALIST_REVISION
            or candidate.get("manifest_sha256") != manifest_digest
            or candidate.get("image_audit_sha256") != sha256(image_audit)
            or key not in candidate.get("candidates", {})
            or candidate.get("test_split_accessed") is not False):
        raise ValueError("J-Lens candidate is not bound to this training/validation cohort")
    selected = candidate["candidates"][key]
    validation_scores = candidate.get("validation_score_rows")
    expected = {row["source_image_path"]: row for row in validation_rows}
    if (not isinstance(validation_scores, list) or len(validation_scores) != len(expected)
            or {row["source_image_path"] for row in validation_scores} != set(expected)):
        raise ValueError("Candidate lacks complete validation image scores")
    for row in validation_scores:
        official = expected[row["source_image_path"]]
        if (row["Patient_ID"] != official["Patient_ID"] or row["trial"] != official["trial"]
                or row["fluid"] != int(official["fluid"])
                or key not in row["scores"] or not math.isfinite(float(row["scores"][key]))):
            raise ValueError("Candidate validation scores do not match expert labels")
    scale = float(selected["scale"])
    intercept = float(selected["intercept"])
    if not math.isfinite(scale) or scale == 0 or not math.isfinite(intercept):
        raise ValueError("Candidate calibration is invalid")
    pairs = [(int(row["fluid"]), scale * float(row["scores"][key])) for row in validation_scores]
    validation_auc = auc(pairs)
    bootstrap = patient_bootstrap_auc(validation_scores, key, scale,
                                      bootstrap_replicates, int(candidate["seed"]))
    jacobian = selected.get("jacobian_submatrix_check", {})
    jacobian_error = float(jacobian.get("max_absolute_error", float("inf")))
    numeric_gate = math.isfinite(jacobian_error) and jacobian_error <= MAX_JACOBIAN_ABSOLUTE_ERROR
    raw_swap_fraction = float(selected["same_prompt_positive_score_higher_fraction"])
    calibrated_swap_fraction = raw_swap_fraction if scale > 0 else 1 - raw_swap_fraction
    image_gate = (
        validation_auc >= MIN_VALIDATION_AUC
        and bootstrap["ci95"][0] > MIN_BOOTSTRAP_AUC_LOWER
        and calibrated_swap_fraction >= MIN_SWAP_POSITIVE_FRACTION
        and float(selected["same_prompt_median_absolute_score_change"]) > 0
        and math.isfinite(float(selected["blank_image_score"]))
        and math.isfinite(float(selected["text_only_score"]))
    )

    model, _ = load_released_specialist(model_dir, authors_code)
    model.eval()
    adapter = adapter_parameters(model.model)
    direction = torch.tensor(selected["direction"], dtype=torch.float32)
    lens = FixedLensHead(direction, scale, intercept).to(model.model.device)
    tensor = tensor_for_row(model, train_rows[0], image_root)
    samples = {"Image": tensor, "Question": [question], "Answer": [""]}
    _, hidden = pre_answer_forward(model.model, samples, layer_index)
    label = torch.tensor([int(train_rows[0]["fluid"])], dtype=torch.float32, device=hidden.device)
    loss = F.binary_cross_entropy_with_logits(lens(hidden), label)
    loss.backward()
    adapter_gradient_norm = sum(float(parameter.grad.float().norm()) for parameter in adapter
                                if parameter.grad is not None)
    non_adapter_gradients = sum(parameter.grad is not None for name, parameter in model.model.named_parameters()
                                if not name.startswith("llama_proj."))
    gradient_gate = math.isfinite(adapter_gradient_norm) and adapter_gradient_norm > 0 and non_adapter_gradients == 0

    # Recompute deterministic scores on 16 validation scans, balanced by label.
    rng = random.Random(int(candidate["seed"]) + layer_index)
    rechecked = []
    for label_value in (0, 1):
        group = sorted((row for row in validation_rows if int(row["fluid"]) == label_value),
                       key=lambda row: row["source_image_path"])
        rechecked.extend(rng.sample(group, min(8, len(group))))
    by_path = {row["source_image_path"]: row for row in validation_scores}
    score_errors = []
    with torch.inference_mode():
        for row in rechecked:
            actual = score_one_image(model.model, tensor_for_row(model, row, image_root),
                                     {layer_index: direction}, question)[layer_index]
            expected_score = float(by_path[row["source_image_path"]]["scores"][key])
            score_errors.append(abs(actual - expected_score))
    max_recheck_error = max(score_errors)
    reproducibility_gate = max_recheck_error <= MAX_SCORE_RECHECK_ERROR
    passed = numeric_gate and image_gate and gradient_gate and reproducibility_gate
    result = {
        "status": ("real_model_lens_validated" if passed else "real_model_lens_gate_failed")
                  if readout_mode == "answer" else
                  ("neutral_real_model_lens_validated" if passed else "neutral_lens_gate_failed"),
        "candidate_sha256": sha256(candidate_path),
        "checkpoint_revision": SPECIALIST_REVISION,
        "manifest_sha256": manifest_digest,
        "image_audit_sha256": sha256(image_audit),
        "layer_index": layer_index,
        "target_layer": candidate["target_layer"],
        "fluid_token_id": candidate["fluid_token_id"],
        "question": question,
        "readout_mode": readout_mode,
        "direction": selected["direction"],
        "scale": scale, "intercept": intercept,
        "validation_auc": validation_auc,
        "patient_bootstrap_auc": bootstrap,
        "same_prompt_calibrated_positive_higher_fraction": calibrated_swap_fraction,
        "same_prompt_median_absolute_score_change": selected["same_prompt_median_absolute_score_change"],
        "blank_image_score": selected["blank_image_score"],
        "text_only_score": selected["text_only_score"],
        "jacobian_submatrix_check": jacobian,
        "adapter_gradient_norm": adapter_gradient_norm,
        "non_adapter_gradient_parameters": non_adapter_gradients,
        "rechecked_validation_scans": len(rechecked),
        "max_score_recheck_error": max_recheck_error,
        "thresholds": {"min_validation_auc": MIN_VALIDATION_AUC,
                       "min_bootstrap_auc_lower": MIN_BOOTSTRAP_AUC_LOWER,
                       "min_swap_positive_fraction": MIN_SWAP_POSITIVE_FRACTION,
                       "max_jacobian_absolute_error": MAX_JACOBIAN_ABSOLUTE_ERROR,
                       "max_score_recheck_error": MAX_SCORE_RECHECK_ERROR},
        "image_signal_gate": image_gate and reproducibility_gate,
        "jacobian_submatrix_gate": numeric_gate,
        "adapter_gradient_gate": gradient_gate,
        "test_split_accessed": False,
        "gpu_name": torch.cuda.get_device_name(0),
        "torch_version": torch.__version__, "cuda_version": torch.version.cuda,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, required=True)
    parser.add_argument("--authors-code", type=Path, required=True)
    parser.add_argument("--official-image-manifest", type=Path, required=True)
    parser.add_argument("--image-audit", type=Path, required=True)
    parser.add_argument("--image-root", type=Path, required=True)
    parser.add_argument("--candidate", type=Path, required=True)
    parser.add_argument("--layer-index", type=int, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--bootstrap-replicates", type=int, default=2000)
    args = parser.parse_args()
    print(json.dumps(run(
        model_dir=args.model_dir, authors_code=args.authors_code,
        manifest=args.official_image_manifest, image_audit=args.image_audit,
        image_root=args.image_root, candidate_path=args.candidate,
        layer_index=args.layer_index, output=args.output,
        bootstrap_replicates=args.bootstrap_replicates,
    ), indent=2))
